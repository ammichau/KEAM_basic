"""Paper results for several specifications side by side (PAPER_RESULTS.md at the repository root):
calibration (parameters, targeted moments against the data, untargeted moments), the
single-factor experiments sized to the 1970s employment rate, the refined cohort accounting, the mechanism
decompositions (counterfactuals, precaution versus hoarding, sensitivity of the split) and robustness.
Every number is read from the output files of the scripts named in each section.

usage: python scripts/write_paper_results.py --specs "CRRA gamma 2 (v4e)=v4e,KPR gamma 2 (v9)=v9" [--out ../../PAPER_RESULTS.md]
       per tag: final_calib_<tag>_full.json, final_results_<tag>.json, extra_experiments_<tag>.json,
       cohorts_refined_<tag>_rel.json and cohorts_refined_<tag>.json, channels_<tag>.json,
       jacobian_channels_<tag>.json, robustness_final_<tag>.json, figures_<tag>/ (missing files are skipped)
"""
import sys, os, json, argparse
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
import numpy as np
from keam.final import calibrate as C

ap = argparse.ArgumentParser()
ap.add_argument("--specs", default="CRRA γ = 2 (v4e)=v4e,KPR γ = 2 (v9)=v9")
ap.add_argument("--notes", default="", help="markdown file with generated notes to append (optional)")
ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "PAPER_RESULTS.md"))
a = ap.parse_args()
PY = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
O = lambda f: os.path.join(PY, "output", f)


def load(f):
    return json.load(open(O(f))) if os.path.exists(O(f)) else None


specs = []
for item in a.specs.split(","):
    label, tag = item.rsplit("=", 1)
    specs.append(dict(label=label, tag=tag, calib=load(f"final_calib_{tag}_full.json"), res=load(f"final_results_{tag}.json"),
                      extra=load(f"extra_experiments_{tag}.json"), coh=load(f"cohorts_refined_{tag}_rel.json"),
                      coh_lvl=load(f"cohorts_refined_{tag}.json"), ch=load(f"channels_{tag}.json"),
                      jac=load(f"jacobian_channels_{tag}.json"), rob=load(f"robustness_final_{tag}.json")))
N = [s["label"] for s in specs]
gap = lambda m: 100 * (m["quit/m rec"] - m["quit/m exp"])
fmt = lambda v, f=".4f": "-" if v is None or (isinstance(v, float) and not np.isfinite(v)) else format(v, f)
L = ["# Paper results: separable CRRA and King-Plosser-Rebelo preferences, γ = 2", "",
     "Generated by `Code26/python/scripts/write_paper_results.py` from the files in `Code26/python/output` named in "
     "each section. All specifications use the corrected simulator (husband returns to employment), a recession cut "
     "of the husband's UI replacement to 15%, a 20% recession fall in the wife's job-finding efficiency, and the "
     "targets recorded in each calibration file (the 13 of `keam/final/calibrate.py` unless a column says otherwise; "
     "quit-targeted versions fix the exogenous separation rate at the married women's layoff rate of "
     "`output/quit_layoff.md` and target its quit rate). The recession wage cut (φ(rec) = φ_H(rec) = 0.88 for the wife's wage and "
     "the husband's income) is present unless the fixed fields set `phi_rec` and `phi_rec_H` to 1. Model: `FINAL_MODEL.md`.", ""]
# ---------------- summary (generated from the same files)
L.append("## Summary\n")
L.append("| | " + " | ".join(N) + " |\n|---|" + "---|" * len(N))
row = lambda name, f: L.append(f"| {name} | " + " | ".join(f(s) for s in specs) + " |")
OBJ = lambda s: C.objective_from_moments(s["calib"]["moments"], *C.targets_of(s["calib"]))
row("objective (own targets)", lambda s: f"{OBJ(s)[0]:.3f} ({len(C.targets_of(s['calib'])[0])} targets)")
row("largest target misses", lambda s: ", ".join(f"{k} {100 * v:+.0f}%" for k, v in sorted(
    OBJ(s)[1].items(), key=lambda kv: -abs(kv[1]))[:3] if "pts" not in k))
row("recession quit drop: precaution / hoarding", lambda s: f"{s['ch']['baseline']['precaution']:.0%} / {s['ch']['baseline']['hoarding']:.0%}" if s["ch"] else "-")
row("recession employment drop (pts): baseline / acyclical husband risk", lambda s: f"{s['ch']['baseline']['dE']:+.2f} / {s['ch']['baseline']['dE_acycH']:+.2f}" if s["ch"] else "-")
row("recession employment drop (pts) at 1970s employment: RoE / comp. wage gap / cost", lambda s: " / ".join(
    f"{m['dE/pop rec-exp (pts)']:+.2f}" for m in s["res"]["experiments"].values()) if s["res"] else "-")
row("cohorts 1940 → 1980 (relative targets): recession employment drop (pts)", lambda s: (
    f"{s['coh']['1940']['m']['dE/pop rec-exp (pts)']:+.2f} → {s['coh']['1980']['m']['dE/pop rec-exp (pts)']:+.2f}") if s["coh"] else "-")
row("cohorts 1940 → 1980: expansion quit rate", lambda s: (
    f"{s['coh']['1940']['m']['quit/m exp']:.4f} → {s['coh']['1980']['m']['quit/m exp']:.4f}") if s["coh"] else "-")
L.append("")
# ---------------- specifications
L.append("## 0. Specifications\n")
L.append("| | " + " | ".join(N) + " |\n|---|" + "---|" * len(N))
desc = {"kpr": "preferences", "kT_mult": "transitory cost shock"}
L.append("| flow utility when employed | " + " | ".join(
    "[c ψ(h) e^{−(κ+κ_T)}]^{1−γ}/(1−γ): fixed costs and shock are proportional consumption taxes; balanced growth"
    if s["calib"]["fixed"].get("kT_mult") else
    ("[c ψ(h) e^{−κ}]^{1−γ}/(1−γ), additive shock κ_T at the quit decision" if s["calib"]["fixed"].get("kpr") else
     "c^{1−γ}/(1−γ) − µh^{1+η}/(1+η) − κ, additive shock κ_T at the quit decision (not balanced-growth consistent)")
    for s in specs) + " |")
L.append("| fixed fields | " + " | ".join(f"`{s['calib']['fixed']}`" for s in specs) + " |")
L.append("| calibration file | " + " | ".join(f"`final_calib_{s['tag']}_full.json` ({s['calib']['n_eval']} evaluations)" for s in specs) + " |")
L.append("")
# ---------------- calibration
L.append("## 1. Calibration of the 1940s cohort: model against data\n")
L.append("Source: `final_calib_<tag>_full.json` (`scripts/calibrate_ls.py`). Deviation relative to the data (recession "
         "employment drop: in points). Objective: weighted sum of squared deviations.\n")
L.append("| target | data | " + " | ".join(N) + " |\n|---|---|" + "---|" * len(N))
TK = list(dict.fromkeys(k for s in specs for k in C.targets_of(s["calib"])[0]))
for k in TK:
    cells = []; tvs = []
    for s in specs:
        T = C.targets_of(s["calib"])[0]; mv = s["calib"]["moments"].get(k, np.nan)
        if k not in T:
            cells.append(f"{mv:.4f} (untargeted)" if np.isfinite(mv) else "-"); continue
        tv = T[k]; tvs.append(round(tv, 4)); dv = (mv - tv) if "pts" in k else 100 * (mv - tv) / tv
        cells.append(f"{mv:.4f} ({dv:+.2f})" if "pts" in k else f"{mv:.4f} ({dv:+.0f}%)")
    L.append(f"| {k} | {' / '.join(f'{v:.4f}' for v in dict.fromkeys(tvs))} | " + " | ".join(cells) + " |")
L.append("| **objective** | | " + " | ".join(f"**{OBJ(s)[0]:.3f}**" for s in specs) + " |")
if any(s["calib"].get("dropped") for s in specs):
    L.append("\nFixed from the data (not calibrated): " + "; ".join(
        f"{s['label']}: " + ", ".join(f"{k} = {s['calib']['x'][k]:.4f}" for k in s["calib"]["dropped"]) for s in specs if s["calib"].get("dropped")) + ".")
L.append("\n| parameter | " + " | ".join(N) + " |\n|---|" + "---|" * len(N))
keys = list(dict.fromkeys(k for s in specs for k in s["calib"]["x"]))
for k in keys:
    L.append(f"| {k} | " + " | ".join(fmt(s["calib"]["x"].get(k)) for s in specs) + " |")
L.append("\nµ, κ̄, κ_m and σ_κ are in utility units under CRRA and in log-consumption units under KPR, so their "
         "levels are not comparable across the two columns.\n")
UNT = [("U rate", None), ("wife share exp", None), ("wife share rec", None), ("cons drop at H job loss exp (%)", None),
       ("cons drop at H job loss rec (%)", None), ("mean assets/monthly HH inc", None),
       ("wife E | husband E", None), ("wife E | husband U", None)]
L.append("Untargeted moments (baseline simulation of `final_results_<tag>.json`; data for the labor-force entry ratio: "
         "Guner, Kulikova and Valladares-Esteban, a wife's monthly entry probability is 60% higher when her husband "
         "loses his job):\n")
L.append("| moment | data | " + " | ".join(N) + " |\n|---|---|" + "---|" * len(N))
for k, dv in UNT:
    L.append(f"| {k} | {fmt(dv, '.2f') if dv else ''} | " + " | ".join(fmt((s['res'] or {}).get('baseline', {}).get(k)) for s in specs) + " |")
L.append("")
# ---------------- experiments
L.append("## 2. Trend to cycle: single-factor experiments sized to the 1970s employment rate (0.73)\n")
L.append("Source: `final_results_<tag>.json` (`scripts/run_final.py`) and `extra_experiments_<tag>.json` "
         "(`scripts/extra_experiments.py`). Each force alone raises employment to the 1970s rate; the wage-gap "
         "experiment holds household income at baseline behaviour (compensated).\n")
EK = [("E/pop", ".3f"), ("dE/pop rec-exp (pts)", "+.2f"), ("quit/m exp", ".4f"), ("quit/m rec", ".4f"), ("__gap", "+.2f"),
      ("wage gap (hourly ratio)", ".3f"), ("share Lifecycle", ".2f"), ("share PT", ".2f"), ("share Career", ".2f"), ("share NiLF", ".2f")]
for s in specs:
    if not s["res"]:
        continue
    cols = {"baseline": s["res"]["baseline"]}; cols.update(s["res"]["experiments"])
    if s["extra"]:
        cols.update(s["extra"]["experiments"])
    L.append(f"**{s['label']}**\n")
    L.append("| moment | " + " | ".join(cols) + " |\n|---|" + "---|" * len(cols))
    for k, f in EK:
        L.append(f"| {'quit gap rec-exp (pts)' if k == '__gap' else k} | " +
                 " | ".join(format(gap(m) if k == "__gap" else m[k], f) for m in cols.values()) + " |")
    L.append("")
# ---------------- cohorts
L.append("## 3. Cohort accounting (cost scale and τ_w solved jointly per cohort)\n")
L.append("Source: `cohorts_refined_<tag>_rel.json` (`scripts/cohorts_refined.py --e-mode relative`): each cohort's "
         "returns to experience from the data; the cost-of-work scale and τ_w (household income compensated) solved "
         "so that the cohort reproduces the data's change in employment since 1940 (added to the model's 1940 rate) "
         "and the data's ratio of wage gaps. Data: employment 0.62, 0.67, 0.71, 0.73, 0.72; wage gap 0.71, 0.74, "
         "0.77, 0.76, 0.77.\n")
CK = [("E/pop", ".3f"), ("dE/pop rec-exp (pts)", "+.2f"), ("quit/m exp", ".4f"), ("quit/m rec", ".4f"), ("__gap", "+.2f"),
      ("wage gap (hourly ratio)", ".3f"), ("share Lifecycle", ".2f"), ("share PT", ".2f"), ("share Career", ".2f"), ("share NiLF", ".2f")]
for which, key, note in [("relative employment targets", "coh", ""), ("employment targets in data levels", "coh_lvl",
                         " (the model's 1940 employment rate is above the data, so later cohorts' level targets imply "
                         "a smaller rise than in the data; shown for comparison)")]:
    for s in specs:
        c = s[key]
        if not c:
            continue
        n = list(c)
        L.append(f"**{s['label']}, {which}**{note}\n")
        L.append("| cohort | " + " | ".join(n) + " |\n|---|" + "---|" * len(n))
        L.append("| cost scale | " + " | ".join(f"{c[x]['cost_scale']:.2f}" + (" (corner)" if c[x].get("corner") else "") for x in n) + " |")
        L.append("| τ_w | " + " | ".join(f"{c[x]['tau_w']:.3f}" for x in n) + " |")
        for k, f in CK:
            L.append(f"| {'quit gap rec-exp (pts)' if k == '__gap' else k} | " +
                     " | ".join(format(gap(c[x]['m']) if k == "__gap" else c[x]['m'][k], f) for x in n) + " |")
        d0, d1 = c[n[0]]["m"]["dE/pop rec-exp (pts)"], c[n[-1]]["m"]["dE/pop rec-exp (pts)"]
        L.append(f"\nRecession employment drop {d0:+.2f} → {d1:+.2f} points ({100 * (d1 / d0 - 1):+.0f}%) from the {n[0]} to "
                 f"the {n[-1]} cohort.\n")
# ---------------- decompositions
L.append("## 4. Decompositions\n")
L.append("### 4a. Mechanism counterfactuals (calibrated parameters held fixed)\n")
L.append("Source: `final_results_<tag>.json`. Share = part of the baseline recession fall in the quit rate removed when "
         "the channel is switched off.\n")
CF = ["acyclical husband risk", "acyclical job finding", "no recession wage cut", "acyclical own job loss"]
L.append("| counterfactual | " + " | ".join(f"{x}: quit gap (pts) | share | ΔE rec-exp (pts)" for x in N) + " |\n|---|" + "---|---|---|" * len(N))
for k in ["baseline"] + CF:
    cells = []
    for s in specs:
        cf = s["res"]["counterfactuals"]; bg = gap(cf["baseline"]); g = gap(cf[k])
        cells.append(f"{g:+.2f} | {'' if k == 'baseline' else format((bg - g) / bg, '+.0%')} | {cf[k]['dE/pop rec-exp (pts)']:+.2f}")
    L.append(f"| {k} | " + " | ".join(cells) + " |")
L.append("")
L.append("### 4b. Precautionary labor supply versus job hoarding\n")
L.append("Source: `channels_<tag>.json` (`scripts/channels.py`). Precaution = share of the recession quit drop removed "
         "when the husband's risk (job loss, job finding, recession UI cut) is made acyclical; hoarding = share removed "
         "when the wife's job-finding efficiency is made acyclical; both = both at once. ΔE: recession employment drop, "
         "baseline and with acyclical husband risk (the employment effect of precautionary labor supply).\n")
L.append("| variant | " + " | ".join(f"{x}: precaution / hoarding / both | ΔE base / acyc. husband" for x in N) + " |\n|---|" + "---|---|" * len(N))
vnames = list(dict.fromkeys(k for s in specs if s["ch"] for k in s["ch"]))
for v in vnames:
    cells = []
    for s in specs:
        r = (s["ch"] or {}).get(v)
        cells.append("- | -" if not r else f"{r['precaution']:.0%} / {r['hoarding']:.0%} / {r['both_off']:.0%} | {r['dE']:+.2f} / {r['dE_acycH']:+.2f}")
    L.append(f"| {v} | " + " | ".join(cells) + " |")
L.append("")
L.append("### 4c. What moves the split: local sensitivity\n")
L.append("Source: `jacobian_channels_<tag>.json` (`scripts/jacobian_channels.py`, +10% steps). Change in the precaution "
         "and hoarding shares (percentage points) per +1% of each quantity.\n")
jn = list(dict.fromkeys(k for s in specs if s["jac"] for k in s["jac"]["points"] if k != "base"))
L.append("| quantity | " + " | ".join(f"{x}: precaution | hoarding" for x in N) + " |\n|---|" + "---|---|" * len(N))
for k in jn:
    cells = []
    for s in specs:
        j = s["jac"]
        if not j or k not in j["points"]:
            cells.append("- | -"); continue
        b, r, st = j["points"]["base"], j["points"][k], 100 * j["step"]
        cells.append(f"{100 * (r['precaution'] - b['precaution']) / st:+.2f} | {100 * (r['hoarding'] - b['hoarding']) / st:+.2f}")
    L.append(f"| {k} | " + " | ".join(cells) + " |")
L.append("")
# ---------------- robustness
L.append("## 5. Robustness (calibrated parameters held fixed)\n")
L.append("Source: `robustness_final_<tag>.json` (`scripts/robustness_final.py`).\n")
rn = list(dict.fromkeys(k for s in specs if s["rob"] for k in s["rob"]))
L.append("| variant | " + " | ".join(f"{x}: E/pop | quit gap | ΔE rec-exp" for x in N) + " |\n|---|" + "---|---|---|" * len(N))
for k in rn:
    cells = []
    for s in specs:
        r = (s["rob"] or {}).get(k)
        cells.append("- | - | -" if not r else f"{r['m']['E/pop']:.3f} | {gap(r['m']):+.2f} | {r['m']['dE/pop rec-exp (pts)']:+.2f}")
    L.append(f"| {k} | " + " | ".join(cells) + " |")
L.append("")
# ---------------- figures
L.append("## 6. Figures (`scripts/figures.py`)\n")
for s in specs:
    fd = O(f"figures_{s['tag']}")
    if os.path.isdir(fd):
        L.append(f"**{s['label']}**: " + ", ".join(f"[{f[:-4]}](Code26/python/output/figures_{s['tag']}/{f})"
                                                   for f in sorted(os.listdir(fd)) if f.endswith(".png")) + "\n")
if a.notes and os.path.exists(a.notes):
    L.append(open(a.notes).read())
open(a.out, "w").write("\n".join(L) + "\n")
print("wrote", a.out)
